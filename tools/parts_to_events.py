#!/usr/bin/env python3
"""Convert a source-identified, measure-validated SATB score to compact FM-1 C events.

Input is MISSA's consciously small note transcription format: independent parts,
diatonic relative pitch, explicit beat lengths, with no lyric or engraving data.
"""
import argparse
import json
from pathlib import Path
import re

PITCH = dict(zip("cdefgab", (0, 2, 4, 5, 7, 9, 11)))
DIATONIC = dict(zip("cdefgab", range(7)))
PARTS = ("S", "A", "T", "B")
TOKEN = re.compile(r"^([a-g])(f?)([',]*):([123])$")


def to_events(score):
    if score.get("format") != "missa-satb-1":
        raise ValueError("wrong score format")
    if score["beats_per_bar"] != 3 or score["ticks_per_beat"] != 96:
        raise ValueError("only 3/4 at 96 ticks per beat currently")
    bars = [score["voices"][p]["bars"] for p in PARTS]
    if not all(len(x) == 32 for x in bars):
        raise ValueError("all parts need exactly 32 measures")
    events = []
    for part, name in enumerate(PARTS):
        data = score["voices"][name]
        if data["anchor"] not in ("c3", "c4"):
            raise ValueError("unsupported relative anchor")
        prev = (3 if data["anchor"] == "c3" else 4) * 7
        tick = 0
        for bar in data["bars"]:
            beats = 0
            for token in bar.split():
                m = TOKEN.fullmatch(token)
                if not m:
                    raise ValueError(f"{name} invalid note {token!r}")
                letter, flat, shift, dur = m.groups()
                letter_idx = DIATONIC[letter]
                idx = min((letter_idx + 7 * n for n in range(1, 8)),
                          key=lambda candidate: abs(candidate - prev))
                idx += 7 * (shift.count("'") - shift.count(","))
                prev = idx
                octave = idx // 7
                pitch = (octave + 1) * 12 + PITCH[letter] - int(bool(flat))
                if not 0 <= pitch <= 127:
                    raise ValueError("MIDI pitch out of range")
                duration = int(dur)
                beats += duration
                span = 96 * duration
                events.extend(((tick, pitch, 96, 1, part),
                               (tick + span, pitch, 0, 0, part)))
                tick += span
            if beats != 3:
                raise ValueError(f"{name} invalid bar duration {beats}")
        if tick != 32*3*96:
            raise ValueError("inconsistent part duration")
    events.sort(key=lambda x: (x[0], x[3], x[4], x[1]))
    return events, 32*3*96


def emit(events, end):
    lines=[
        "/* SPDX-License-Identifier: CC0-1.0 */",
        "/* Four-voice public-domain GROSSER GOTT; see data/hymns metadata.",
        " * Generated by tools/parts_to_events.py; score notes only. */",
        "#pragma once",
        '#include "music_engine.h"',
        "static const missa_event missa_holy_god[] = {"
    ]
    lines.extend("    {"+",".join(map(str,e))+"}," for e in events)
    lines.extend((
        "};",
        f"#define MISSA_HOLY_GOD_END {end}u",
        "#define MISSA_HOLY_GOD_COUNT ((uint16_t)(sizeof missa_holy_god / sizeof missa_holy_god[0]))",
        "",
    ))
    return "\n".join(lines)


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("source",type=Path)
    ap.add_argument("output",type=Path)
    ap.add_argument("--check",action="store_true")
    args=ap.parse_args()
    events,end=to_events(json.loads(args.source.read_text(encoding="utf-8")))
    result=emit(events,end)
    if args.check:
        if args.output.read_text(encoding="utf-8") != result:
            raise SystemExit("generated SATB header is stale")
    else:
        args.output.write_text(result,encoding="utf-8")
    print(f"SATB: {len(events)//2} notes, four parts, {end} ticks")


if __name__ == "__main__":
    main()
